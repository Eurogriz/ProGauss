def _nums(block: str) -> list[float]:
    return [float(m) for m in re.findall(r"[+-]?\d+\.?\d*(?:[eE][+-]?\d+)?", block)]


def verify_against_source(src: Path) -> None:
    """Повторно парсит исходники s-dftd3 и сверяет со вложенным снимком."""
    ref = (src / "src" / "dftd3" / "reference.f90").read_text()
    i = ref.index("number_of_references(max_elem) = [")
    nref_all = [int(x) for x in re.findall(r"\d+", ref[i : ref.index("]", i)])]
    nref = {int(z): int(v) for z, v in _RAW["nref"].items()}
    for z in ELEMENTS:
        if nref_all[z - 1] != nref[z]:
            raise AssertionError(f"nref(Z={z}): {nref_all[z - 1]} != {nref[z]}")
    i = ref.index("reference_cn(max_ref, max_elem) = reshape([")
    end = ref.index("[max_ref, max_elem])", i)
    refcn_flat = _nums(ref[i:end])
    refcn = {int(z): tuple(float(x) for x in v) for z, v in _RAW["refcn"].items()}
    for z in ELEMENTS:
        got = tuple(refcn_flat[7 * (z - 1) + k] for k in range(nref[z]))
        if any(abs(a - b) > 1e-12 for a, b in zip(got, refcn[z])):
            raise AssertionError(f"refcn(Z={z}): {got} != {refcn[z]}")
    pos = ref.index("c6ab_view(1:2000)")
    c6flat: list[float] = []
    while len(c6flat) < 262444:
        j = ref.index("c6ab_view(", pos)
        m = re.match(r"c6ab_view\(\s*(\d+)\s*:\s*\d+\s*\)\s*=\s*\[", ref[j:])
        endj = ref.index("]", j)
        assert int(m.group(1)) - 1 == len(c6flat), "разрыв в c6ab_view"
        c6flat.extend(_nums(ref[j:endj][ref[j:endj].index("[") + 1 :]))
        pos = endj
    assert len(c6flat) == 262444
    for p in _RAW["c6_pairs"]:
        z_lo, z_hi = int(p["z_lo"]), int(p["z_hi"])
        ic = int(p["ic"]) - 1
        nlo, nhi = int(p["n_lo"]), int(p["n_hi"])
        got = [c6flat[a_hi + 7 * a_lo + 49 * ic] for a_hi in range(nhi) for a_lo in range(nlo)]
        want = [float(v) for v in p["values"]]
        if any(abs(a - b) > 1e-12 for a, b in zip(got, want)):
            raise AssertionError(f"c6 pair ({z_lo},{z_hi}): расхождение")
    r4f = (src / "src/dftd3/data/r4r2.f90").read_text()
    i = r4f.index("r4_over_r2(max_elem) = [")
    r4_all = _nums(r4f[i : r4f.index("]", i)][r4f[i : r4f.index("]", i)].index("[") + 1 :])
    r4raw = {int(z): float(v) for z, v in _RAW["r4raw"].items()}
    for z in ELEMENTS:
        if abs(r4_all[z - 1] - r4raw[z]) > 1e-12:
            raise AssertionError(f"r4raw(Z={z}): {r4_all[z - 1]} != {r4raw[z]}")
    cov = (src / "src/dftd3/data/covrad.f90").read_text()
    i = cov.index("covalent_rad_2009(max_elem) = aatoau * [")
    cov_all = _nums(cov[i : cov.index("]", i)][cov[i : cov.index("]", i)].index("[") + 1 :])
    rcov = {int(z): float(v) for z, v in _RAW["rcov_2009_angstrom"].items()}
    for z in ELEMENTS:
        if abs(cov_all[z - 1] - rcov[z]) > 1e-12:
            raise AssertionError(f"covrad(Z={z}): {cov_all[z - 1]} != {rcov[z]}")
    vrf = (src / "src/dftd3/data/vdwrad.f90").read_text()
    i = vrf.index("vdwrad(max_elem*(1+max_elem)/2) = aatoau * [")
    endv = vrf.index("]", i)
    vdw_all = _nums(vrf[i:endv][vrf[i:endv].index("[") + 1 :])
    for p in _RAW["vdw_pairs"]:
        z_lo, z_hi = int(p["z_lo"]), int(p["z_hi"])
        ic = z_lo + z_hi * (z_hi - 1) // 2 - 1
        if abs(vdw_all[ic] * AATOA_D3 - float(p["vdw_bohr"])) > 1e-9:
            raise AssertionError(f"vdw pair ({z_lo},{z_hi}): расхождение")
    print("verify: все значения совпадают с исходниками s-dftd3")


def generate(out_path: Path) -> None:
    nref = {int(z): int(v) for z, v in _RAW["nref"].items()}
    refcn = {int(z): tuple(float(x) for x in v) for z, v in _RAW["refcn"].items()}
