def _format_in_place(out_path: Path) -> None:
    """Прогоняет сгенерированный файл через ``ruff format``, если ruff есть.

    Генератор обязан выдавать код, который проходит ``make lint`` (включая
    ``ruff format --check``). Если ruff недоступен, пропускаем и предупреждаем:
    в dev-окружении (``pip install -e .[dev]``) он всегда установлен.
    """
    if shutil.which("ruff") is None and _ruff_as_module() is None:
        print("предупреждение: ruff не найден — пропущен ruff format")
        return
    cmd = _ruff_command()
    result = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        msg = f"ruff format завершился с ошибкой: {result.stderr.strip()}"
        raise RuntimeError(msg)


def _ruff_as_module() -> bool:
    try:
        import importlib.util

        return importlib.util.find_spec("ruff") is not None
    except Exception:  # noqa: BLE001 - любая ошибка интерпретируется как «нет ruff»
        return False


def _ruff_command() -> list[str]:
    if shutil.which("ruff") is not None:
        return ["ruff", "format"]
    return [sys.executable, "-m", "ruff", "format"]


