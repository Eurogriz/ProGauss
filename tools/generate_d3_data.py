def pair_index(z_lo: int, z_hi: int) -> int:
    """Номер пары элементов (нумерация с 1): ``z_lo + z_hi·(z_hi−1)/2``."""
    if z_lo > z_hi:
        z_lo, z_hi = z_hi, z_lo
    return z_lo + z_hi * (z_hi - 1) // 2


def nref_of(z: int) -> int:
    """Число справочных состояний элемента."""
    return _ELEMENTS[z].nref


def c6_lookup(z_lo: int, z_hi: int, a_hi: int, a_lo: int) -> float:
    """C6 для пары элементов и справочных индексов (порядок таблицы).

    ``a_lo`` — индекс справочного состояния элемента ``z_lo``,
    ``a_hi`` — элемента ``z_hi``; плоский индекс ``a_hi·nref(z_lo)+a_lo``.
    """
    vals = C6_PAIRS[(z_lo, z_hi)]
    return vals[a_hi * nref_of(z_lo) + a_lo]


def vdw_pair(z_lo: int, z_hi: int) -> float:
    """Вандерваальсов радиус пары, bohr (zero-затухание, r0).

    Аргументы можно передавать в любом порядке — пара хранится
    по (min Z, max Z).
    """
    lo, hi = (z_lo, z_hi) if z_lo <= z_hi else (z_hi, z_lo)
    return VDW_PAIRS[(lo, hi)]


