def element_data(z: int) -> D3ElementData:
    """Данные D3 для элемента; ``ValueError`` вне области применения."""
    try:
        return _ELEMENTS[z]
    except KeyError:
        raise ValueError(f"элемент Z={z} вне области применения D3: {D3_ELEMENTS}") from None


